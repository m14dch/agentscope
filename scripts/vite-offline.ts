/**
 * Vite plugin (01-architecture.yaml deployment offline_mechanics): after the build has
 * written dist/, lists every file in it, writes asset-manifest.json and generates sw.js
 * from the service worker template with that manifest inlined.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

export const MANIFEST_FILE = 'asset-manifest.json';
export const SERVICE_WORKER_FILE = 'sw.js';

export type PrecacheManifest = {
  /** The build's version stamp (commit SHA in CI, "dev" locally). */
  version: string;
  /** One combined hash over every listed file's path and bytes and the worker template. */
  hash: string;
  /**
   * Every file in dist relative to the base path, sorted, with its Subresource Integrity
   * digest; excludes the manifest and sw.js.
   */
  files: PrecachedFile[];
};

export type PrecachedFile = { path: string; integrity: string };

export type BuiltFile = { path: string; content: Uint8Array };

/** Every file under a directory, with POSIX paths relative to it. */
export function readBuild(dir: string): BuiltFile[] {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => {
      const absolute = join(entry.parentPath, entry.name);
      return {
        path: relative(dir, absolute).split(sep).join('/'),
        content: readFileSync(absolute),
      };
    });
}

/** The Subresource Integrity digest of some bytes (sha256-<base64>). */
export function integrity(content: Uint8Array): string {
  return `sha256-${createHash('sha256').update(content).digest('base64')}`;
}

/**
 * The manifest of a build. The service worker template feeds the hash too, so a changed
 * worker gets a new cache name even when no other file changed.
 */
export function precacheManifest(
  files: readonly BuiltFile[],
  version: string,
  template = '',
): PrecacheManifest {
  const listed = files
    .filter((file) => file.path !== MANIFEST_FILE && file.path !== SERVICE_WORKER_FILE)
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const hash = createHash('sha256');
  for (const file of listed) {
    hash.update(file.path).update('\0').update(file.content).update('\0');
  }
  hash.update(SERVICE_WORKER_FILE).update('\0').update(template);
  return {
    version,
    hash: hash.digest('hex').slice(0, 16),
    files: listed.map((file) => ({ path: file.path, integrity: integrity(file.content) })),
  };
}

/** The service worker: the manifest as a constant, then the template. */
export function serviceWorkerSource(manifest: PrecacheManifest, template: string): string {
  return `const PRECACHE = ${JSON.stringify(manifest)};\n${template}`;
}

export function offlinePlugin(templatePath: string, version: string): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'agentscope-offline',
    apply: 'build',
    configResolved(resolved) {
      config = resolved;
    },
    // After every output file, the copied public directory included, is on disk.
    closeBundle: {
      order: 'post',
      handler() {
        const outDir = resolve(config.root, config.build.outDir);
        for (const generated of [MANIFEST_FILE, SERVICE_WORKER_FILE]) {
          if (config.publicDir && existsSync(join(config.publicDir, generated))) {
            throw new Error(`${generated} is generated by the build; remove it from public/.`);
          }
        }
        const template = readFileSync(templatePath, 'utf8');
        const manifest = precacheManifest(readBuild(outDir), version, template);
        writeFileSync(join(outDir, MANIFEST_FILE), `${JSON.stringify(manifest, null, 2)}\n`);
        writeFileSync(join(outDir, SERVICE_WORKER_FILE), serviceWorkerSource(manifest, template));
      },
    },
  };
}
